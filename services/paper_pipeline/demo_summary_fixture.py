def _admit_demo_summary(
    collection: PaperCollection, candidate: PaperCollectionCandidate
) -> PaperSummaryArtifactContent:
    pipeline = PaperSummaryPipeline(clock=lambda: _SUMMARY_TIME)
    result = pipeline.admit(
        paper_collection=collection,
        paper_collection_version_id=_COLLECTION_ARTIFACT_VERSION_ID,
        paper_id=candidate.canonical_paper_id,
        model_response=build_demo_model_response(candidate),
        model_name=_MODEL_NAME,
        parameters=_MODEL_PARAMETERS,
        evidence_candidates=build_demo_evidence_candidates(candidate),
        run_id=None,
    )
    if (
        result.admission_status is not PaperSummaryAdmissionStatus.accepted
        or result.summary is None
    ):
        raise ValueError(
            "demo summary fixture must be accepted by the real pipeline: "
            f"{result.failure_stage}"
        )
    return result.summary


def build_demo_summary() -> PaperSummaryArtifactContent:
    """Run the real PaperSummary Pipeline admission against the real Paper Acquisition Workspace demo collection."""

    collection = build_demo_collection()
    return _admit_demo_summary(collection, _select_demo_candidate(collection))


def build_demo_summary_read() -> tuple[PaperSummaryRead, ArtifactVersionDetail]:
    """Project the admitted summary through the PaperSummary API read shape."""

    collection = build_demo_collection()
    candidate = _select_demo_candidate(collection)
    summary = _admit_demo_summary(collection, candidate)
    content = summary.model_dump(mode="json", exclude_none=False)
    content_hash = compute_canonical_payload_hash(content)
    pipeline_snapshot = collection.source_snapshots[0]
    reference = summary.input_versions.source_snapshots[0]
    if reference.source_snapshot_id != pipeline_snapshot.snapshot_id:
        raise ValueError("summary input snapshot does not match the collection")
    # PaperSummary API re-links summary snapshot references to persisted snapshots by the
    # (source_id, source_version_or_etag, content_hash) key, so the persisted
    # detail must pin the exact source_version the pipeline derived.
    snapshot_detail = SourceSnapshotDetail(
        id=_SNAPSHOT_DETAIL_ID,
        source_id=pipeline_snapshot.source_id,
        source_type=pipeline_snapshot.source_type,
        retrieved_at=pipeline_snapshot.retrieved_at,
        query=pipeline_snapshot.query,
        query_hash=pipeline_snapshot.query_hash,
        source_version_or_etag=reference.source_version,
        content_hash=pipeline_snapshot.content_hash,
        license_note=pipeline_snapshot.license_note,
        cache_version=pipeline_snapshot.cache_version,
        request_metadata=pipeline_snapshot.request_metadata,
    )
    producer = summary.producer
    producer_execution = ProducerExecutionDetail(
        id=_PRODUCER_EXECUTION_ID,
        run_id=_RUN_ID,
        step_key=producer.step_key,
        step_attempt_id=_STEP_ATTEMPT_ID,
        producer=ProducerReference(
            type=producer.producer_type,
            name=producer.producer_name,
            version=producer.producer_version,
            model_name=producer.model_name,
            prompt_name=producer.prompt_name,
            prompt_version=producer.prompt_version,
            prompt_hash=producer.prompt_hash,
            parameters_hash=producer.parameters_hash,
        ),
        parameters=dict(_MODEL_PARAMETERS),
        parameters_hash=producer.parameters_hash,
        input_hash=summary.input_hash,
        output_hash=content_hash,
        status="completed",
        started_at=producer.started_at,
        finished_at=producer.finished_at,
        latency_ms=producer.latency_ms,
        error_code=None,
    )
    # Each retained summary Evidence must be persisted exactly once as a
    # generic Evidence row targeting a statement that references it, with the
    # summary source_record_id inside the locator (PaperSummary API cross-link check).
    statement_by_evidence: dict[str, str] = {}
    for statement in summary.statements():
        for evidence_id in statement.evidence_ids:
            statement_by_evidence[evidence_id] = statement.statement_id
    evidence = tuple(
        EvidenceDetail(
            id=f"evd_papsum_{index + 1:02d}",
            artifact_version_id=_ARTIFACT_VERSION_ID,
            target_type="paper_summary",
            target_id=statement_by_evidence[item.evidence_id],
            evidence_type=item.locator.kind,
            source_snapshot_id=_SNAPSHOT_DETAIL_ID,
            paper_id=item.paper_id,
            locator={
                "kind": item.locator.kind,
                "summary_evidence_id": item.evidence_id,
                "source_record_id": item.source_record_id,
                "source_url": str(item.locator.source_url),
                **(
                    {"metadata_field": item.locator.metadata_field}
                    if item.locator.kind == "paper_metadata"
                    # The generic domain `PaperTextLocator` reads `range`;
                    # `text_range` exists only inside the summary schema.
                    else {
                        "section": item.locator.section,
                        "range": item.locator.text_range,
                    }
                ),
            },
            quote_or_value=item.quote_or_value,
            extraction_method="paper_summary",
            confidence=1.0,
            created_at=producer.finished_at,
        )
        for index, item in enumerate(summary.evidence)
    )
    read = PaperSummaryRead(
        artifact_version_id=_ARTIFACT_VERSION_ID,
        artifact_id=_ARTIFACT_ID,
        project_id=_PROJECT_ID,
        version_number=1,
        supersedes_version_id=None,
        source_mode=SourceMode.fixture,
        content_hash=content_hash,
        input_hash=summary.input_hash,
        created_at=producer.finished_at,
        paper=PaperSummaryPaperMetadata(
            paper_id=candidate.canonical_paper_id,
            title=candidate.title,
            authors=candidate.authors,
            year=candidate.year,
        ),
        summary=summary,
        cache_audits=(),
        producer_execution=producer_execution,
        source_snapshots=(snapshot_detail,),
        evidence=evidence,
    )
    # The generic ArtifactVersion identity must be derived from the exact
    # same canonical PaperSummary dump: PaperSummary API recomputes content_hash over
    # version.content and cross-checks schema/producer fields.
    version = ArtifactVersionDetail(
        id=_ARTIFACT_VERSION_ID,
        artifact_id=_ARTIFACT_ID,
        project_id=_PROJECT_ID,
        created_by_run_id=_RUN_ID,
        version_number=1,
        schema_version=summary.schema_version,
        content=content,
        content_hash=content_hash,
        input_hash=summary.input_hash,
        source_mode=SourceMode.fixture,
        producer=producer_execution.producer,
        source_snapshot_ids=(snapshot_detail.id,),
        evidence_ids=tuple(item.id for item in evidence),
        supersedes_version_id=None,
        created_at=producer.finished_at,
        producer_execution=producer_execution,
        source_snapshots=(snapshot_detail,),
        evidence=evidence,
    )
    return read, version


def build_summary_fixture_document() -> dict[str, Any]:
    read, version = build_demo_summary_read()
    return {
        "$generated": {
            "tool": "services.paper_pipeline.demo_summary_fixture",
            "command": (
                "uv run --project apps/api python -m "
                "services.paper_pipeline.demo_summary_fixture"
            ),
            "scenario_id": DEMO_SCENARIO_ID,
            "benchmark_id": read.summary.benchmark.benchmark_id,
            "benchmark_version": read.summary.benchmark.benchmark_version,
            "paper_id": read.summary.paper_id,
            "paper_collection_version_id": (
                read.summary.input_versions.paper_collection_version_id
            ),
            "provenance_note": SUMMARY_PROVENANCE_NOTE,
        },
        "read": read.model_dump(mode="json", exclude_none=False),
        "artifact_version": version.model_dump(mode="json", exclude_none=False),
    }


FIXTURE_OUTPUT_PATH = (
    Path(__file__).resolve().parents[2]
    / "packages"
    / "data-access"
    / "src"
    / "fixture"
    / "paper-summary.fixture.json"
)


def main() -> None:
    document = build_summary_fixture_document()
    FIXTURE_OUTPUT_PATH.write_text(
        json.dumps(document, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"wrote {FIXTURE_OUTPUT_PATH}")


if __name__ == "__main__":
    main()
