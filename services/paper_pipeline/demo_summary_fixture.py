_SUMMARY_TIME = datetime(2026, 7, 21, 8, 25, tzinfo=timezone.utc)

_ARTIFACT_VERSION_ID = "artv_papsum_01"
_ARTIFACT_ID = "art_papsum_01"
_SNAPSHOT_DETAIL_ID = "snap_papsum_crossref_01"
_PRODUCER_EXECUTION_ID = "pexec_run_papsum_01"
_STEP_ATTEMPT_ID = "att_papsum_01"
_MODEL_NAME = "fixture-model"
_MODEL_PARAMETERS: dict[str, float | int] = {"temperature": 0, "top_p": 1}

SUMMARY_PROVENANCE_NOTE = (
    "Demo Replay fixture generated by the real PaperSummaryPipeline "
    "over the deterministic Paper Acquisition Workspace demo PaperCollection (frozen benchmark "
    f"scenario {DEMO_SCENARIO_ID}). The summarized paper is the first "
    "selected non-synthetic candidate; every Evidence quote is derived from "
    "that candidate's raw record. The model response is a deterministic "
    "fixture payload that deliberately exercises the supported, unsupported "
    "and unverifiable statuses. This is not a live model call."
)


def _select_demo_candidate(collection: PaperCollection) -> PaperCollectionCandidate:
    """Pick the summarized paper: first selected, non-synthetic candidate."""

    return next(
        candidate
        for candidate in collection.candidates
        if candidate.selected and candidate.raw.synthetic_note is None
    )


def build_demo_evidence_candidates(
    candidate: PaperCollectionCandidate,
) -> tuple[PaperSummaryEvidenceCandidate, ...]:
    """Evidence anchored on the real collection candidate and its snapshot.

    Three paper_metadata quotes equal the candidate's raw metadata values, so
    the pipeline verifies them as supported. The paper_text quote carries no
    accessible excerpt, so the pipeline must classify it unverifiable.
    """

    if (
        candidate.raw.url is None
        or candidate.raw.year is None
        or candidate.raw.doi is None
    ):
        raise ValueError("demo summary candidate must carry url, year and doi")
    anchor = {
        "paper_id": candidate.canonical_paper_id,
        "candidate_id": candidate.candidate_id,
        "source_id": candidate.raw.source_id,
        "source_record_id": candidate.raw.source_record_id,
        "source_snapshot_id": candidate.raw.source_snapshot_id,
    }
    return (
        PaperSummaryEvidenceCandidate(
            evidence_id="ev.goal_title",
            locator=PaperSummaryEvidenceLocator(
                kind="paper_metadata",
                source_url=candidate.raw.url,
                metadata_field="title",
            ),
            quote_or_value=candidate.raw.title,
            **anchor,
        ),
        PaperSummaryEvidenceCandidate(
            evidence_id="ev.dataset_year",
            locator=PaperSummaryEvidenceLocator(
                kind="paper_metadata",
                source_url=candidate.raw.url,
                metadata_field="year",
            ),
            quote_or_value=str(candidate.raw.year),
            **anchor,
        ),
        PaperSummaryEvidenceCandidate(
            evidence_id="ev.finding_doi",
            locator=PaperSummaryEvidenceLocator(
                kind="paper_metadata",
                source_url=candidate.raw.url,
                metadata_field="doi",
            ),
            quote_or_value=candidate.raw.doi,
            **anchor,
        ),
        # No accessible_excerpt: the real pipeline must not verify this quote
        # and has to admit it as unverifiable (evidence.source_text_unavailable).
        PaperSummaryEvidenceCandidate(
            evidence_id="ev.method_text",
            locator=PaperSummaryEvidenceLocator(
                kind="paper_text",
                source_url=candidate.raw.url,
                section="Methods",
                text_range="paragraph 2, sentences 1-3",
            ),
            quote_or_value=(
                "Stellar parameters are compiled from all-sky photometric "
                "catalogs and parallax measurements."
            ),
            accessible_excerpt=None,
            **anchor,
        ),
    )


