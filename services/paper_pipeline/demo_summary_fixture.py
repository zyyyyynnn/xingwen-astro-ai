"""Deterministic literature-summary demo fixture built by the production pipeline.

This module exists so the frontend paper-summary Fixture is generated by the
authoritative Python contract chain instead of being hand-written in
TypeScript. It reuses the deterministic Paper Acquisition Workspace ``build_demo_collection()`` as
the Paper Acquisition Pipeline provenance input, drives the real ``PaperSummaryPipeline.admit``
(prompt registry, parameter hashing, Evidence cross-checks against the real
collection candidate and SourceSnapshot, output hashing), then projects the
admitted ``PaperSummaryArtifactContent`` through the same read shape PaperSummary API
serves (``PaperSummaryRead``) plus the immutable ``ArtifactVersionDetail``.

Nothing is hand-transcribed: the summarized paper is the first selected,
non-synthetic candidate of the demo collection, and every Evidence quote is
derived from that candidate's raw bibliographic record. The model response is
a deterministic ``PaperSummaryModelOutput`` payload deliberately exercising
all three support statuses: supported statements verified against real
paper_metadata, one unsupported statement carrying no Evidence at all, and
one unverifiable paper_text statement whose source excerpt is unavailable.

Regenerate the committed JSON with:

    uv run --project apps/api python -m services.paper_pipeline.demo_summary_fixture
    pnpm prettier --write packages/data-access/src/fixture/paper-summary.fixture.json

The prettier pass is mandatory after every regeneration: this generator
writes plain ``json.dumps`` output, while the repo formatting gate
(`pnpm format:check`) collapses short arrays onto one line.
"""

