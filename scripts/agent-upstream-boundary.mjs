export function isForbiddenVendoredProductPath(upstreamPath) {
  const normalized = upstreamPath.replaceAll("\\", "/").toLowerCase();
  return (
    FORBIDDEN_PREFIXES.some((prefix) => normalized.startsWith(prefix)) ||
    FORBIDDEN_FRAGMENTS.some((fragment) => normalized.includes(fragment))
  );
}
